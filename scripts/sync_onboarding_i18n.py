def escape_android(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', '\\"')
        .replace("'", "\\'")
        .replace("\n", "\\n")
    )


def upsert_json_locale(locale: str) -> None:
    path = ROOT / "shared/src/commonMain/resources/i18n" / locale / "strings.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    for key, locales in STRINGS.items():
        data[key] = locales[locale]
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def upsert_xcstrings() -> None:
    path = ROOT / "iosApp/OmniGart/Localizable.xcstrings"
    catalog = json.loads(path.read_text(encoding="utf-8"))
    strings = catalog.setdefault("strings", {})
    for key, locales in STRINGS.items():
        entry = strings.setdefault(key, {"extractionState": "manual", "localizations": {}})
        locs = entry.setdefault("localizations", {})
        for locale, value in locales.items():
            locs[locale] = {"stringUnit": {"state": "translated", "value": value}}
    path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def upsert_android_xml(locale: str) -> None:
    rel = ANDROID_LOCALE_DIR[locale]
    path = ROOT / "androidApp/src/main/res" / rel / "strings.xml"
    # Also update default values/ from en-GB
    targets = [path]
    if locale == "en-GB":
        targets.append(ROOT / "androidApp/src/main/res/values/strings.xml")
    for target in targets:
        text = target.read_text(encoding="utf-8")
        for key, locales in STRINGS.items():
            value = escape_android(
                locales["en-GB"] if target.parent.name == "values" else locales[locale]
            )
            pattern = re.compile(rf'<string name="{re.escape(key)}">.*?</string>', re.DOTALL)
            replacement = f'<string name="{key}">{value}</string>'
            if pattern.search(text):
                text = pattern.sub(replacement, text)
            else:
                text = text.replace("</resources>", f"    {replacement}\n</resources>")
        target.write_text(text, encoding="utf-8")


def main() -> None:
    for locale in LOCALES:
        upsert_json_locale(locale)
        upsert_android_xml(locale)
    upsert_xcstrings()
    print(f"Synced {len(STRINGS)} keys × {len(LOCALES)} locales")


if __name__ == "__main__":
    main()
