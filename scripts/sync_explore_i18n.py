def humanize(eid: str) -> str:
    return EN_LABELS.get(eid, eid.replace("_", " ").title())


def load_json(path: Path) -> dict:
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(dict(sorted(data.items())), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    # shared i18n json
    for loc in LOCALES:
        path = ROOT / "shared/src/commonMain/resources/i18n" / loc / "strings.json"
        data = load_json(path)
        for key, mapping in UI.items():
            data[key] = mapping.get(loc) or mapping["en-GB"]
        for eid in EQUIP_IDS:
            data[f"equipment_item_{eid}"] = humanize(eid) if loc == "en-GB" else data.get(f"equipment_item_{eid}") or humanize(eid)
        # For non-en, keep existing translations if present; otherwise en label (machine draft)
        if loc != "en-GB":
            for eid in EQUIP_IDS:
                k = f"equipment_item_{eid}"
                if k not in data or data[k] == humanize(eid):
                    # Prefer prior sync_tabs values when already translated
                    pass
        for key, en in ROUTINES_EN.items():
            # Store routine keys also in shared for UI fallback; content locales hold exercise names
            if loc == "en-GB":
                data[key] = en
            else:
                data.setdefault(key, en)
        write_json(path, data)

    # Android values XML helpers — merge via sync_tabs later; write en-GB + default
    # iOS xcstrings — append keys via sync_tabs pattern: run a minimal merge into Localizable.xcstrings
    xc = ROOT / "iosApp/OmniGart/Localizable.xcstrings"
    catalog = json.loads(xc.read_text(encoding="utf-8"))
    strings = catalog.setdefault("strings", {})
    for key, mapping in UI.items():
        entry = strings.setdefault(key, {"localizations": {}})
        locs = entry.setdefault("localizations", {})
        for loc, text in mapping.items():
            locs[loc] = {"stringUnit": {"state": "translated", "value": text}}
    for eid in EQUIP_IDS:
        key = f"equipment_item_{eid}"
        entry = strings.setdefault(key, {"localizations": {}})
        locs = entry.setdefault("localizations", {})
        for loc in LOCALES:
            locs.setdefault(loc, {"stringUnit": {"state": "translated", "value": humanize(eid)}})
    for key, en in ROUTINES_EN.items():
        entry = strings.setdefault(key, {"localizations": {}})
        locs = entry.setdefault("localizations", {})
        for loc in LOCALES:
            locs.setdefault(loc, {"stringUnit": {"state": "translated", "value": en}})
    xc.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    # Android strings: patch values/strings.xml and locale folders with a simple append of missing names
    res = ROOT / "androidApp/src/main/res"
    locale_dirs = {
        "en-GB": res / "values-en-rGB",
        "uk": res / "values-uk",
        "pl": res / "values-pl",
        "be": res / "values-be",
        "kk": res / "values-kk",
        "ka": res / "values-ka",
        "es": res / "values-es",
        "fr": res / "values-fr",
        "de": res / "values-de",
        "cs": res / "values-cs",
        "zh-Hans": res / "values-zh-rCN",
    }
    default_xml = res / "values" / "strings.xml"

    def upsert_xml(path: Path, pairs: dict[str, str]) -> None:
        text = path.read_text(encoding="utf-8") if path.exists() else '<resources>\n</resources>\n'
        for key, value in pairs.items():
            esc = (
                value.replace("&", "&amp;")
                .replace("'", r"\'")
                .replace('"', r"\"")
            )
            line = f'    <string name="{key}">{esc}</string>'
            if f'name="{key}"' in text:
                text = re.sub(rf'    <string name="{re.escape(key)}">.*?</string>', line, text)
            else:
                text = text.replace("</resources>", f"{line}\n</resources>")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    write_targets: list[tuple[str, Path]] = [("en-GB", res / "values")]
    write_targets += [(loc, folder) for loc, folder in locale_dirs.items()]
    for loc, folder in write_targets:
        pairs = {}
        for key, mapping in UI.items():
            pairs[key] = mapping.get(loc) or mapping["en-GB"]
        for eid in EQUIP_IDS:
            pairs[f"equipment_item_{eid}"] = humanize(eid)
        for key, en in ROUTINES_EN.items():
            pairs[key.replace(".", "_")] = en  # android names can't have dots — skip dotted keys
        # Only write non-dotted keys to XML
        xml_pairs = {k: v for k, v in pairs.items() if "." not in k}
        upsert_xml(folder / "strings.xml", xml_pairs)

    print(f"equip ids={len(EQUIP_IDS)} ui keys={len(UI)} routines={len(ROUTINES_EN)}")


if __name__ == "__main__":
    main()
