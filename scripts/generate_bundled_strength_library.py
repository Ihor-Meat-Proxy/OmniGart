#!/usr/bin/env python3
"""Regenerate BundledStrengthLibrary.kt from content/exercises/data/*.json."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "content/exercises/data"
OUT = ROOT / "shared/src/commonMain/kotlin/com/omnigart/shared/strength/BundledStrengthLibrary.kt"

def fraction(ex: dict) -> float:
    raw = ex.get("bodyweightFraction")
    if isinstance(raw, dict):
        return float(raw.get("proportion") or 0.0)
    if isinstance(raw, (int, float)):
        return float(raw)
    return 0.0


def load_model(ex: dict) -> str:
    model = ex.get("loadModel")
    if model:
        return str(model)
    tracking = ex.get("trackingType") or ""
    if tracking in {"bodyweight_reps", "bodyweight_hold", "reps"} and "bodyweight" in (ex.get("equipment") or []):
        return "bodyweight_plus_external"
    return "external_only"


def links(ex: dict, key: str) -> list[str]:
    out: list[str] = []
    for item in ex.get(key) or []:
        if isinstance(item, dict) and item.get("exerciseId"):
            out.append(str(item["exerciseId"]))
        elif isinstance(item, str):
            out.append(item)
    return out


def kotlin_list(values: list[str]) -> str:
    if not values:
        return "listOf()"
    if len(values) <= 2 and sum(len(v) for v in values) < 60:
        inner = ", ".join(f'"{v}"' for v in values)
        return f"listOf({inner})"
    lines = ",\n".join(f'                "{v}"' for v in values)
    return f"listOf(\n{lines}\n            )"


def emit_exercise(ex: dict) -> str:
    frac = fraction(ex)
    model = load_model(ex)
    if model == "external_only":
        frac = 0.0
    return f"""        StrengthLibraryExercise(
            id = "{ex["id"]}",
            movementPattern = "{ex.get("movementPattern") or "other"}",
            primaryMuscles = {kotlin_list(list(ex.get("primaryMuscles") or []))},
            secondaryMuscles = {kotlin_list(list(ex.get("secondaryMuscles") or []))},
            equipment = {kotlin_list(list(ex.get("equipment") or ["bodyweight"]))},
            level = "{ex.get("level") or "intermediate"}",
            mechanics = "{ex.get("mechanics") or "compound"}",
            unilateral = {"true" if ex.get("unilateral") else "false"},
            loadModel = "{model}",
            bodyweightFraction = {frac},
            allowsAddedWeight = {"true" if ex.get("allowsAddedWeight") else "false"},
            allowsAssistance = {"true" if ex.get("allowsAssistance") else "false"},
            regressions = {kotlin_list(links(ex, "regressions"))},
            progressions = {kotlin_list(links(ex, "progressions"))}
        )"""


def main() -> None:
    exercises: list[dict] = []
    for path in sorted(DATA.glob("*.json")):
        ex = json.loads(path.read_text(encoding="utf-8"))
        if (ex.get("discipline") or "") != "strength":
            continue
        exercises.append(ex)

    by_id = {ex["id"]: ex for ex in exercises}
    ordered = [by_id[k] for k in sorted(by_id)]

    body = ",\n".join(emit_exercise(ex) for ex in ordered)
    text = f"""package com.omnigart.shared.strength

/**
 * Offline strength exercise index for the equipment-aware program generator.
 * Ids match `content/exercises/data`; equipment tags follow the expanded catalogue.
 *
 * Generated by scripts/generate_bundled_strength_library.py — do not hand-edit.
 */
object BundledStrengthLibrary {{
    val exercises: List<StrengthLibraryExercise> = listOf(
{body}
    )
}}
"""
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {len(ordered)} exercises → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
